	lea	verify_field_lines(pc),a0
	move.l	#263,(a0)
.pal
	ENDC
	move.l	version(pc),d0
	subq.l	#2,d0
	cmp.l	#2,d0
	bhi.b	.done
	add.w	d0,d0
	lea	version_deltas(pc),a1
	adda.w	d0,a1
	lea	version_refs(pc),a0
	lea	_base(pc),a2
.next
	moveq	#0,d0
	move.w	(a0)+,d0
	beq.b	.done
	move.w	(a0)+,d1
	move.w	(a1,d1.w),d2
	add.w	d2,(a2,d0.l)
	bra.b	.next
.done
	movem.l	(sp)+,d0-d2/a0-a2
	rts

