"""Independent active-time message policy and native evidence validator."""
import argparse
from pathlib import Path
import struct

DURATION = 178  # ceil(3 seconds * approximately 59.11 native PAL CIA ticks/second)


def remaining(deadline, now):
    distance = (deadline - now) & 0xffffffff
    return distance if distance < 2**31 else 0


def legacy(intervals):
    return max(1, (intervals * 15000 + DURATION - 1) // DURATION)


def shortened(value):
    return max(0, (value * DURATION + 14999) // 15000)


def emit(path):
    path.write_text('; Generated by tools/message_time.py; do not edit.\ntime_message_cases:\n' +
                    ''.join(f'\tdc.w {legacy(n)}\n' for n in range(DURATION + 1)))


def check_capture(log, count, initial_count, rows, erasures, native_test, pointers):
    def require(condition, message):
        if not condition:
            raise ValueError(message)
    require(native_test == 179, 'Incomplete native message arithmetic checks')
    require(0 <= initial_count <= count < 128 and len(log) >= count * 24,
            'Invalid or saturated message ledger')
    require(len(pointers) == 3 and len(set(pointers)) == 3 and 0 not in pointers,
            'Invalid fixture message pointers')
    events = [struct.unpack_from('>II4HII', log, i * 24) for i in range(initial_count, count)]
    fixture = [e for e in events if e[7] in pointers]
    starts = [e[7] for e in fixture if e[2] == 1]
    shortens = [e for e in fixture if e[2] == 2]
    require(starts == [*pointers, pointers[0]], 'Missing/extra fixture message or replacement')
    require([e[7] for e in shortens] == [pointers[1], pointers[0]] and
            all(e[4] == 5000 for e in shortens), 'Missing fixture shortening')
    # Early shortened text can legitimately be replaced by combat. The final
    # two fixture lifetimes must complete, including one shortened lifetime.
    late = fixture[fixture.index(next(e for e in fixture if e[7] == pointers[2])):]
    require([e[2] for e in late] in ([1, 3, 4, 1, 2, 3, 4], [1, 3, 1, 2, 3, 4]),
            'Full and shortened late lifetimes did not complete')
    current = None
    expiry_count = 0
    replacement_count = 0
    for i, event in enumerate(events):
        now, deadline, kind, phase, timer, dirty, draws, pointer = event
        if kind == 1:
            if current is not None and current[3] == 2:
                require(dirty == 2, 'Pending replacement lost old-rectangle cleanup')
                replacement_count += 1
            require(((deadline - now) & 0xffffffff) == DURATION and phase == 1 and timer == 15000,
                    f'Wrong three-second arm at event {i}')
        elif kind == 2:
            require(current is not None and pointer == current[7] and phase == 1 and
                    0 <= timer <= 15000 and
                    ((deadline - now) & 0xffffffff) == shortened(timer),
                    f'Wrong shortening policy at event {i}')
        elif kind == 3:
            require(current is not None and current[3] == 1 and
                    (deadline, pointer) == (current[1], current[7]) and
                    now == deadline and phase == 2 and timer == 1 and dirty == 2,
                    f'Expiry must occur on its active-time deadline and dirty both buffers ({i})')
            expiry_count += 1
        elif kind == 4:
            require(current is not None and current[3] == 2 and
                    (deadline, pointer) == (current[1], current[7]) and
                    phase == 0 and timer == 0 and remaining(deadline, now) == 0,
                    f'Premature render erasure at event {i}')
        else:
            require(False, f'Unknown event kind at event {i}')
        current = event
    require(len(erasures) + replacement_count == expiry_count and all(e[1:3] == [0, 2] for e in erasures),
            'Native erasure did not republish two-buffer dirtiness')
    exercised = set()
    for tick, now, phase, timer, dirty, draws, deadline, pointer in rows:
        # Ledger and observations share the simulation cursor. At a tied cursor,
        # retain their recorded phase to distinguish a later main-task fixture call.
        require(phase in (0, 1, 2), f'Invalid message phase at world tick {tick}')
        if phase == 1:
            left = remaining(deadline, now)
            require(0 < left <= DURATION and timer == legacy(left),
                    f'Render count or Time Scale changed message age at world tick {tick}')
        elif phase == 2:
            require(remaining(deadline, now) == 0 and timer == 1,
                    f'Expired message lost its pending erasure at world tick {tick}')
        else:
            require(timer == 0, f'Erased message still has a timer at world tick {tick}')
        if pointer in pointers:
            exercised.add(phase)
    require({0, 1, 2} <= exercised, 'Did not observe live, expired-pending and erased states')
    require(rows[-1][2:5] == [0, 0, 0], 'Final dirty-buffer work is unfinished')
    return dict(events=len(events), fixture_events=len(fixture), world_observations=len(rows),
                lifetime_CIA_intervals=DURATION, exact_expiry=True,
                native_erasures=len(erasures), pending_replacements=replacement_count, final_dirty_count=0)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit', type=Path, required=True)
    emit(parser.parse_args().emit)
