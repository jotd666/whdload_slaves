"""Exact sim:2c31c register/CCR model and bounded exponent candidate.

The original preserves D2 with MOVE.L, so final N/Z describe the caller's D2.
Zero preserves input X; nonzero clears it. D0's upper word is significant.
"""
import argparse
from pathlib import Path
import random

MASK=0xffffffff


def finish(value,d2,ccr,zero):
    flags=(8 if d2&0x80000000 else 4 if d2==0 else 0)
    if zero:flags|=ccr&16
    return value&MASK,0,d2&MASK,flags


def original(value,d2,ccr):
    value&=MASK;d2&=MASK
    if not value:return finish(0,d2,ccr,True)
    scan=value;exponent=-1
    while scan:exponent+=1;scan>>=1
    while True:
        carry=value>>31;value=(value<<1)&MASK
        if carry:break
    value=((value<<16)|(value>>16))&MASK
    value=(value&0xffff0000)|((value&65535)>>8)
    value=(value&0xffff0000)|(((value&65535)+(exponent<<8))&65535)
    return finish(value,d2,ccr,False)


def candidate(value,d2,ccr):
    value&=MASK;d2&=MASK
    if not value:return finish(0,d2,ccr,True)
    scan=value;exponent=0
    if scan>=0x10000:
        # Native SWAP then ANDI.L: discard the original low word.
        scan=((scan<<16)|(scan>>16))&0xffff;exponent=16
    for shift in (8,4,2,1):
        if scan>=1<<shift:scan>>=shift;exponent+=shift
    value=(value<<(32-exponent))&MASK
    value=((value<<16)|(value>>16))&MASK
    value=(value&0xffff0000)|((value&65535)>>8)|(exponent<<8)
    return finish(value,d2,ccr,False)


def cases():
    values={0,1,MASK,0x80000000,0x12345678,0xabcdef01}
    for bit in range(32):
        for delta in (-1,0,1):values.add(((1<<bit)+delta)&MASK)
    rng=random.Random(0x2c31c)
    values.update(rng.getrandbits(32) for _ in range(64))
    return [(v,d2,original(v,d2,0)[0]) for v in sorted(values) for d2 in (0,1,0x80000000,MASK)]


def emit(path):
    rows=cases()
    text=['; Generated by exponent_encode.py; each row runs all 32 input CCRs.',
          f'TIME_EXP_CASE_COUNT = {len(rows)}','time_exp_cases:']
    text.extend('\tdc.l '+','.join(f'${v:08x}' for v in row) for row in rows)
    path.write_text('\n'.join(text)+'\n')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--emit',type=Path,required=True)
    emit(p.parse_args().emit)
