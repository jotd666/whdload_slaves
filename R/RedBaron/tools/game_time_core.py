"""Integer reference and assembly-vector generator for W6's one-CIA-tick core.

A common denominator preserves exact fractional world time across every F=10..80
change without division, rounding or growing rational state on the 68000.
The caller retains unprocessed CIA ticks as debt and advances this core one tick
at a time, interleaving due world updates and input in timestamp order.
"""
from math import lcm
from pathlib import Path
import argparse
import random

DENOMINATOR = lcm(*range(10, 81))
QUANTUM = 225
THRESHOLD = DENOMINATOR * QUANTUM
MASK128 = (1 << 128)-1


def advance(credit, secondary, divisor, multiplier=1):
    if not 0 <= credit < THRESHOLD or not 0 <= secondary < 2560:
        raise ValueError('Core input must contain only the unspent fractional phase')
    if not 10 <= divisor <= 80 or multiplier not in (1, 8):
        raise ValueError('Invalid clock rate')
    total = credit + (DENOMINATOR // divisor)*1024*multiplier
    if total > MASK128:
        raise OverflowError('World phase exceeded 128 bits')
    world, credit = divmod(total, THRESHOLD)
    service, secondary = divmod(secondary+1024, 2560)
    return credit, secondary, world, service


def limbs(value):
    return [(value >> shift) & 0xffffffff for shift in (96, 64, 32, 0)]


def dc(value):
    return '\tdc.l '+','.join(f'${v:08x}' for v in limbs(value))+'\n'


def vectors():
    rng = random.Random(603)
    for divisor in range(10, 81):
        for multiplier in (1, 8):
            for credit in (0, THRESHOLD-1, rng.randrange(THRESHOLD)):
                secondary = rng.choice((0, 1535, 1536, 2559))
                yield credit, secondary, divisor, multiplier, advance(credit, secondary, divisor, multiplier)


def write_includes(directory):
    rates = '; Generated by tools/game_time_core.py; exact rational clock constants.\n'
    rates += 'time_core_threshold:\n'+dc(THRESHOLD)
    rates += 'time_core_rates:\n'
    for divisor in range(10, 81):
        rates += f'; F={divisor}\n'+dc((DENOMINATOR//divisor)*1024)
    (directory/'time-core-rates.i').write_text(rates)
    cases = list(vectors())
    out = '; Generated native CPU cases, tested against the rational host oracle.\n'
    out += f'TIME_CORE_CASE_COUNT = {len(cases)}\ntime_core_cases:\n'
    for credit, secondary, divisor, multiplier, result in cases:
        phase, service_phase, world, service = result
        out += dc(credit)+f'\tdc.w {secondary},{divisor},{multiplier},0\n'
        out += dc(phase)+f'\tdc.w {service_phase},{world},{service},0\n'
    (directory/'time-core-cases.i').write_text(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    write_includes(args.source)
