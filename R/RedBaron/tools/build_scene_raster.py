"""Build freestanding PC-relative scene kernels into reviewable assembler data."""
import argparse
from pathlib import Path
import subprocess
import tempfile

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--prefix',default=str(Path.home()/'.local/opt/bin/m68k-amiga-elf-'))
p.add_argument('--objcopy',default=str(Path.home()/'.local/opt/m68k-amiga-elf/bin/objcopy'))
a=p.parse_args()
root=Path(__file__).resolve().parents[1]
for source,entry,label in [('scene_raster.c','rb_scene','scene_raster_code'),
                           ('fast_blitter_model.c','rb_blit','scene_compat_code')]:
 with tempfile.TemporaryDirectory(prefix='redbaron-scene-build-') as tmp:
  tmp=Path(tmp);obj=tmp/'kernel.o';elf=tmp/'kernel.elf';binary=tmp/'kernel.bin'
  script=tmp/'kernel.ld';script.write_text('SECTIONS { . = 0; .text : { *(.text.entry) *(.text*) *(.rodata*) } /DISCARD/ : { *(.comment) *(.eh_frame) } }')
  subprocess.run([a.prefix+'gcc','-O3','-m68020','-mpcrel','-fomit-frame-pointer',
                  '-ffreestanding','-fno-builtin','-fno-jump-tables','-fno-stack-protector',
                  '-fno-unwind-tables','-fno-asynchronous-unwind-tables',
                  '-c',str(root/'tools'/source),'-o',str(obj)],check=True)
  subprocess.run([a.prefix+'ld','-T',str(script),'-e',entry,'--emit-relocs',str(obj),'-o',str(elf)],check=True)
  rel=subprocess.check_output([a.prefix+'objdump','-r',str(elf)],text=True)
  if 'R_68K_32' in rel or 'R_68K_16' in rel:raise RuntimeError('Absolute relocation in kernel: '+rel)
  subprocess.run([a.objcopy,'-O','binary','--only-section=.text',str(elf),str(binary)],check=True)
  data=binary.read_bytes();assert len(data)%2==0
  out=root/'usr/source'/('scene-raster.i' if entry=='rb_scene' else 'scene-compat.i')
  words=[f'${int.from_bytes(data[i:i+2],"big"):04x}' for i in range(0,len(data),2)]
  out.write_text('; Generated by tools/build_scene_raster.py; source: tools/'+source+'\n'+label+':\n'+''.join(' dc.w '+','.join(words[i:i+8])+'\n' for i in range(0,len(words),8)))
  print(out.name,len(data),'bytes')
