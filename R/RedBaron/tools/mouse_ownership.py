"""Independent camera/world mouse ownership oracle and native interleaving vectors."""
import argparse
from pathlib import Path
from mouse_replay import accumulate, control

CENTER = (160, 100)


def advance(state, operation):
    world, camera = state
    kind, dx, dy, lx, ly = operation
    if kind == 0:
        world = (accumulate(world[0], dx, lx), accumulate(world[1], dy, ly))
        camera = (accumulate(camera[0], dx, lx), accumulate(camera[1], dy, ly))
    elif kind == 1:
        world = CENTER
    elif kind == 2:
        camera = CENTER
    else:
        raise ValueError('Unknown mouse owner operation')
    return world, camera


def vectors():
    state = (CENTER, CENTER)
    movements = ((1, -1), (127, 127), (-128, -128), (8, -8), (0, 127), (-127, 0))
    for index in range(24):
        dx, dy = movements[index % len(movements)]
        operations = [(0, dx, dy, 319, 199), (1, 0, 0, 0, 0),
                      (0, dy, dx, 319, 199), (0, dx, dy, 319, 199),
                      (2, 0, 0, 0, 0), (0, -dx, -dy, 319, 199),
                      (2, 0, 0, 0, 0), (1, 0, 0, 0, 0)]
        for operation in operations:
            state = advance(state, operation)
            yield (*operation, *state[0], *state[1])


def emit(path):
    cases = list(vectors())
    path.write_text('; Generated by tools/mouse_ownership.py; do not edit.\n'
                    'time_mouse_ownership_cases:\n' + f'\tdc.w {len(cases)}\n' +
                    ''.join('\tdc.w ' + ','.join(f'${n & 0xffff:04x}' for n in row) +
                            '\n' for row in cases))


def check_camera_capture(rows, posts, cameras, native_cases):
    """Mouse-only fixture: camera follows world construction on each native loop.

    The final breakpoint is before its camera call, so one fewer camera row is
    expected. Different service schedules are covered by the native vectors.
    """
    def require(condition, message):
        if not condition:
            raise ValueError(message)
    require(native_cases == 192, 'Incomplete native mouse ownership vectors')
    require(len(rows) == len(posts) and len(cameras) == len(rows) - 1 and cameras,
            'Missing camera observations')
    for row, post, camera in zip(rows, posts, cameras):
        cx, mx = control(row[3], 160)
        cy, my = control(row[4], 100)
        # The camera uses native gain four versus the flight control gain six.
        require(camera[:3] == [row[0], cx >> 2, cy >> 2],
                f'Camera lost or duplicated mouse movement at tick {row[0]}')
        require(camera[3:5] == post[3:5], 'Camera recentered flight input')
        expected = [160, 100] if mx or my else row[3:5]
        require(camera[5:7] == expected, 'Camera reset its wrong private position')
        require(camera[7] == post[5] + int(mx or my), 'Missing/extra native camera reset')
    return dict(native_camera_observations=len(cameras), ownership_vectors=native_cases)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit', type=Path, required=True)
    emit(parser.parse_args().emit)
