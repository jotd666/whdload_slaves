"""Exact W6 presentation arithmetic; never changes a simulation state.

Position lerp rounds toward negative infinity. Angles take the signed shortest
16-bit arc; exactly half a turn chooses the negative arc deterministically.
Q16 endpoints 0 and 65536 are exact. Interior phase conversion truncates once.
"""
import argparse
from fractions import Fraction
from pathlib import Path
import random
from game_time_core import THRESHOLD, limbs


def position(old, new, fraction):
    if not -(1 << 31) <= old < 1 << 31 or not -(1 << 31) <= new < 1 << 31:
        raise ValueError('Position outside signed long')
    if not 0 <= fraction <= 65536:
        raise ValueError('Blend fraction outside Q16 interval')
    value = Fraction(old) + Fraction((new-old)*fraction, 65536)
    return value.numerator // value.denominator


def angle(old, new, fraction):
    if not 0 <= old <= 65535 or not 0 <= new <= 65535:
        raise ValueError('Angle outside unsigned word')
    delta = ((new-old+32768) & 65535)-32768
    return position(old, old+delta, fraction) & 65535


def phase_fraction(phase):
    if not 0 <= phase < THRESHOLD:
        raise ValueError('Due world ticks must be drained before interpolation')
    return phase*65536 // THRESHOLD


def vectors():
    rng = random.Random(615)
    for mode, endpoints in [(0, [-2147483648, -65537, -1, 0, 1, 65537, 2147483647]),
                            (1, [0, 1, 32767, 32768, 65534, 65535])]:
        function = angle if mode else position
        for old in endpoints:
            for new in endpoints:
                for fraction in (0, 1, 32767, 32768, 65535, 65536):
                    yield mode, old, new, fraction, function(old, new, fraction)
        for _ in range(64):
            old, new = (rng.randrange(65536) for _ in range(2)) if mode else (rng.randrange(-2147483648, 2147483648) for _ in range(2))
            fraction = rng.randrange(65537)
            yield mode, old, new, fraction, function(old, new, fraction)


def phase_vectors():
    rng = random.Random(616)
    for phase in [0, 1, THRESHOLD-1, THRESHOLD//2, THRESHOLD//2-1,
                  *[rng.randrange(THRESHOLD) for _ in range(128)]]:
        yield phase, phase_fraction(phase)


def write_cases(path):
    cases = list(vectors())
    phases = list(phase_vectors())
    out = '; Generated by tools/presentation_math.py from rational arithmetic.\n'
    out += f'TIME_PRESENT_CASES = {len(cases)}\nTIME_PRESENT_PHASE_CASES = {len(phases)}\n'
    out += 'time_present_cases:\n'
    for mode, old, new, fraction, expected in cases:
        out += '\tdc.l '+','.join(f'${value & 0xffffffff:08x}' for value in (mode, old, new, fraction, expected))+'\n'
    out += 'time_present_phase_cases:\n'
    for phase, expected in phases:
        out += '\tdc.l '+','.join(f'${v:08x}' for v in limbs(phase)+[expected])+'\n'
    path.write_text(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    write_cases(parser.parse_args().output)
