"""Word-accurate mouse accumulation and independent native flight-control oracle."""
import argparse
import struct
from pathlib import Path

FIXTURE = ((2, 1, 0), (4, 2, -1), (10, -4, 3), (18, 127, 127),
           (20, 127, 127), (26, -128, -128), (28, -128, -128),
           (34, -128, -128), (42, 127, -128), (50, 0, 127),
           (58, -1, 1), (66, 8, -8))


def signed(value, bits):
    value &= (1 << bits) - 1
    return value - (1 << bits) if value >> (bits - 1) else value


def delta(previous, current):
    return signed(current - previous, 8)


def accumulate(position, movement, limit):
    total = signed(position + movement, 16)
    return 0 if total < 0 else min(total, limit & 0xffff)


def control(position, center):
    # Native sim:1e8be/1e8d2 clamp, then sim:1ebc2 dead zone/response (gain 6).
    value = max(-127, min(127, signed((position - center) * 8, 16)))
    adjusted = value + (value >> 4) - 8 if value > 8 else (
        value + (value >> 4) + 8 if value < -8 else 0)
    return adjusted >> 2, value != 0


def vectors():
    for limit in (199, 319, 0x7fff, 0xffff):
        for position in (0, 1, 100, 160, 198, 199, 318, 319, 0x7fff, 0x8000, 0xffff):
            for movement in (-128, -127, -1, 0, 1, 127):
                yield position, movement & 0xffff, limit, accumulate(position, movement, limit)


def emit(path):
    cases = list(vectors())
    text = '; Generated by tools/mouse_replay.py; do not edit.\ntime_mouse_cases:\n'
    text += f'\tdc.w {len(cases)}\n'
    text += ''.join('\tdc.w ' + ','.join(f'${x:04x}' for x in row) + '\n' for row in cases)
    path.write_text(text)


def check_capture(queue, acq, counters, rows, posts, epoch, keyboard_counters, arithmetic_cases):
    """Check acquisition packets against native input, control and reset records."""
    def require(condition, message):
        if not condition:
            raise ValueError(message)

    produced, consumed, resets = struct.unpack('>III', counters)
    head, tail, overflow, high = struct.unpack_from('>4H', queue)
    require((produced, consumed, head, tail, overflow) == (12, 12, 12, 12, 0)
            and 1 <= high <= 12, 'Missing/extra mouse events or queue fault')
    require(keyboard_counters == bytes(8), 'Mouse motion leaked into keyboard commands')
    require(arithmetic_cases == 264, 'Incomplete native mouse arithmetic test')
    require(rows and len(rows) == len(posts), 'Missing native input/control observations')
    events = []
    for i, (threshold, ex, ey) in enumerate(FIXTURE):
        wall, paused, dx, dy, lx, ly = struct.unpack_from('>IIhhHH', acq, i * 16)
        require((dx, dy, lx, ly) == (ex, ey, 319, 199),
                f'Wrong acquired mouse movement/limits at event {i}')
        require(((wall - epoch) & 0xffffffff) >= threshold,
                f'Premature fixture acquisition at event {i}')
        deadline = (wall - paused + 1) & 0xffffffff
        require(struct.unpack_from('>IHhhHHH', queue, 16 + i * 16) ==
                (deadline, 0x201, dx, dy, lx, ly, 0),
                f'Mouse event differs from its acquisition at event {i}')
        events.append((deadline, dx, dy, lx, ly))
    x, y = 160, 100
    at = moving = multi = last_resets = 0
    previous_moved = False
    for row, post in zip(rows, posts):
        tick, cursor, now, inx, iny, px, py = row
        before = at
        while at < 12 and ((cursor - events[at][0]) & 0xffffffff) < 2**31:
            _, dx, dy, lx, ly = events[at]
            at += 1
            x, y = accumulate(x, dx, lx), accumulate(y, dy, ly)
        require((inx, iny, px, py) == (x, y, x, y),
                f'Wrong mouse input or retroactive movement at tick {tick}')
        cx, mx = control(x, 160)
        cy, my = control(y, 100)
        require(tuple(post[:3]) == (tick, cx, cy), f'Wrong native control at tick {tick}')
        reset_delta = post[5] - last_resets
        moved = mx or my
        require(int(moved) <= reset_delta <= int(moved) + int(previous_moved),
                f'Missing/extra native reset at tick {tick}')
        if moved:
            x, y = 160, 100
            moving += 1
        previous_moved = moved
        last_resets = post[5]
        if at - before > 1:
            multi += 1
        require(tuple(post[3:5]) == (x, y), f'Wrong private reset at tick {tick}')
    require(at == 12 and moving and multi and last_resets == resets,
            'Incomplete mouse movement/accumulation/reset coverage')
    return dict(events=12, rows=len(rows), moving_world_ticks=moving,
                multiple_acquisition_ticks=multi, acquisition_deadlines=True,
                native_controls=True, native_resets=resets, queue_high_water=high,
                native_arithmetic_cases=264,
                max_observed_CIA_debt=max((r[2] - r[1]) & 0xffffffff for r in rows))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit', type=Path, required=True)
    emit(parser.parse_args().emit)
